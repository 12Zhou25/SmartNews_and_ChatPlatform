async def seed_data():
    """插入示例数据（如果表为空）"""
    print("=" * 50)
    print("正在检查并插入示例数据...")

    async with AsyncSessionLocal() as session:
        # 检查分类表是否已有数据
        result = await session.execute(select(func.count(Category.id)))
        cat_count = result.scalar_one()

        if cat_count > 0:
            print(f"[SKIP] 新闻分类表已有 {cat_count} 条数据，跳过插入")
        else:
            for cat_data in SAMPLE_CATEGORIES:
                session.add(Category(**cat_data))
            await session.commit()
            print(f"[OK] 插入 {len(SAMPLE_CATEGORIES)} 个新闻分类")

        # 检查新闻表是否已有数据
        result = await session.execute(select(func.count(News.id)))
        news_count = result.scalar_one()

        if news_count > 0:
            print(f"[SKIP] 新闻表已有 {news_count} 条数据，跳过插入")
        else:
            now = datetime.now()
            for i, news_data in enumerate(SAMPLE_NEWS):
                news_data_with_time = {
                    **news_data,
                    "views": (len(SAMPLE_NEWS) - i) * 100 + 50,
                    "publish_time": now - timedelta(hours=i * 6),
                }
                session.add(News(**news_data_with_time))
            await session.commit()
            print(f"[OK] 插入 {len(SAMPLE_NEWS)} 条示例新闻")

        # 检查用户表是否已有数据
        result = await session.execute(select(func.count(User.id)))
        user_count = result.scalar_one()

        if user_count > 0:
            print(f"[SKIP] 用户表已有 {user_count} 条数据，跳过插入")
        else:
            # 创建一个测试用户
            test_user = User(
                username="admin",
                password=get_hash_password("123456"),
                nickname="管理员",
                gender="unknown",
                bio="测试账号，密码: 123456",
            )
            session.add(test_user)
            await session.commit()
            print("[OK] 创建测试用户: admin / 123456")

    print("=" * 50)
    print("数据库初始化完成！")
    print()
    print("测试账号:")
